//---------------- FUNCTIONS  ----------------
let add = function(a, b){
    console.log(a+" + "+b+" = "+(a+b));
}

let substract = function(a, b){
    console.log(a+" - "+b+" = "+(a-b));
}

let multiply = function(a, b){
    console.log(a+" x "+b+" = "+(a*b));
}

let divide = function(a, b){
    console.log(a+" / "+b+" = "+(a/b));
}
add(10, 2);
substract(10, 2);
multiply(10, 2);
divide(10, 2);