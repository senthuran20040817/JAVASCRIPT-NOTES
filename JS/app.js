//---------------- FUNCTIONS  ----------------
function add(a, b){
    console.log(a+" + "+b+" = "+(a+b));
}

function substract(a, b){
    console.log(a+" - "+b+" = "+(a-b));
}

function multiply(a, b){
    console.log(a+" x "+b+" = "+(a*b));
}

function divide(a, b){
    console.log(a+" / "+b+" = "+(a/b));
}

add(10, 2);
substract(10, 2);
multiply(10, 2);
divide(10, 2);