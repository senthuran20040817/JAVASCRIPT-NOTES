//---------------- FUNCTIONS  ----------------
function add(a, b){
    return a+b;
}

function substract(a, b){
    return a-b;
}

function multiply(a, b){
    return a*b;
}

function divide(a, b){
    return a/b;
}

console.log("Addition       => "+add(10, 2));
console.log("Substraction   => "+substract(10, 2));
console.log("Multiplication => "+multiply(10, 2));
console.log("Division       => "+divide(10, 2));
